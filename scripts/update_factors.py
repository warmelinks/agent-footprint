#!/usr/bin/env python3
"""Refresh the per-person baselines from Our World in Data.

    python scripts/update_factors.py            # rewrite src/agent_footprint/data/countries.json
    python scripts/update_factors.py --check    # only report what would change (exit 1 if anything)

For the world and every country it takes the latest year of
- electricity generation per person (Ember, via Our World in Data), and
- greenhouse-gas emissions per person including land use (Jones et al., via Our World in Data),
and stores them per day. Prints a Markdown summary for the pull request the monthly workflow
opens, and flags changes over 25% for a closer look. Standard library only.
"""
import argparse
import csv
import io
import json
import os
import sys
import urllib.request
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "agent_footprint", "data", "countries.json")
GRAPHER = "https://ourworldindata.org/grapher/%s"
SERIES = {
    # key: (grapher slug, unit per year -> unit per day factor, unit stored)
    "energy": ("per-capita-electricity-generation", 1000 / 365, "Wh"),   # kWh/person/year -> Wh/day
    "carbon": ("per-capita-ghg-emissions", 1e6 / 365, "g CO2e"),         # t/person/year -> g/day
}
BIG_CHANGE = 0.25


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "agent-footprint factor updater"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def latest(slug):
    """{code: (entity name, year, value)} with each entity's most recent year."""
    text = fetch(GRAPHER % slug + ".csv?v=1&csvType=full&useColumnShortNames=true")
    rows = csv.reader(io.StringIO(text))
    header = [h.strip().lstrip("\ufeff").lower() for h in next(rows)]
    i_ent, i_code, i_year = header.index("entity"), header.index("code"), header.index("year")
    i_val = len(header) - 1
    out = {}
    for row in rows:
        code = row[i_code]
        if code == "OWID_WRL":
            code = "WLD"
        if len(code) != 3 or not row[i_val]:
            continue  # regions and income groups have OWID_ codes or none
        year, value = int(row[i_year]), float(row[i_val])
        if code not in out or year > out[code][1]:
            out[code] = (row[i_ent], year, value)
    return out


def source(slug):
    meta = json.loads(fetch(GRAPHER % slug + ".metadata.json"))
    col = next(iter(meta["columns"].values()))
    return {"title": col.get("titleShort") or col.get("title"), "citation": col.get("citationShort"),
            "url": GRAPHER % slug, "updated": col.get("lastUpdated"), "next_update": col.get("nextUpdate")}


def build():
    countries, sources = {}, {}
    for key, (slug, per_day, unit) in SERIES.items():
        sources[key] = dict(source(slug), unit_per_day=unit)
        for code, (name, year, value) in latest(slug).items():
            c = countries.setdefault(code, {"name": name})
            c[key] = {"per_day": round(value * per_day, 1), "year": year}
    return {"_about": "Per-person daily baselines, generated by scripts/update_factors.py from Our World in Data. "
                      "Do not edit by hand.",
            "generated": date.today().isoformat(), "sources": sources,
            "countries": dict(sorted(countries.items()))}


def summary(old, new):
    lines, big = [], []
    oc, nc = old.get("countries", {}), new["countries"]
    for code in ["WLD"] + sorted(set(nc) - {"WLD"}):
        for key in SERIES:
            a, b = (oc.get(code) or {}).get(key), (nc.get(code) or {}).get(key)
            if a == b or b is None:
                continue
            if a is None:
                if code == "WLD":
                    lines.append("- %s %s: new, %s (%d)" % (nc[code]["name"], key, b["per_day"], b["year"]))
                continue
            rel = (b["per_day"] - a["per_day"]) / a["per_day"] if a["per_day"] else 0
            line = "- %s %s: %s (%d) -> %s (%d), %+.1f%%" % (nc[code]["name"], key, a["per_day"], a["year"],
                                                          b["per_day"], b["year"], rel * 100)
            if abs(rel) > BIG_CHANGE:
                big.append(line)
            elif code == "WLD" or len(lines) < 40:
                lines.append(line)
    out = ["Per-person baselines refreshed from Our World in Data (%s)." % new["generated"], ""]
    if big:
        out += ["**Changes over %d%%, please check:**" % (BIG_CHANGE * 100)] + big + [""]
    out += lines or ["No value changes (metadata only)."]
    return "\n".join(out), bool(big)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="report only; exit 1 if the data changed")
    p.add_argument("--summary", help="also write the Markdown summary to this file")
    args = p.parse_args()
    try:
        with open(OUT, encoding="utf-8") as f:
            old = json.load(f)
    except (OSError, ValueError):
        old = {}
    new = build()
    world = new["countries"].get("WLD", {})
    if not (5000 < world.get("energy", {}).get("per_day", 0) < 20000 and
            10000 < world.get("carbon", {}).get("per_day", 0) < 30000):
        sys.exit("World values look wrong, not writing: %s" % world)
    text, _ = summary(old, new)
    print(text)
    if args.summary:
        with open(args.summary, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    changed = {k: v for k, v in old.items() if k != "generated"} != {k: v for k, v in new.items() if k != "generated"}
    if args.check:
        sys.exit(1 if changed else 0)
    if changed:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as f:
            json.dump(new, f, indent=1, ensure_ascii=False)
            f.write("\n")


if __name__ == "__main__":
    main()
